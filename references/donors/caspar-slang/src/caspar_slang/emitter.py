from __future__ import annotations

from .intrinsics import helper_source, lower_scalar_line
from .ir import AccessKind, KernelIR


def _resource_decl(binding: int, name: str, access: AccessKind, scalar_type: str = "float") -> str:
    if access is AccessKind.READ:
        typ = f"StructuredBuffer<{scalar_type}>"
    else:
        typ = f"RWStructuredBuffer<{scalar_type}>"
    return f"[[vk::binding({binding}, 0)]] {typ} {name};"


def emit_slang(kernel: KernelIR) -> str:
    kernel.validate()

    resources = []
    for binding, buf in enumerate(kernel.buffers):
        resources.append(_resource_decl(binding, buf.name, buf.access, buf.scalar_type))

    params_binding = len(kernel.buffers)
    params = ["uint problem_size;"]
    params.extend(f"uint {b.name}_num_alloc;" for b in kernel.buffers if b.num_alloc_param)

    register_decl = ""
    if kernel.registers:
        register_decl = "    float " + " = 0.0f, ".join(kernel.registers) + " = 0.0f;\n"

    code = "\n".join(f"    {lower_scalar_line(line)}" for line in kernel.code_lines)

    return f"""// Generated by caspar-slang. Do not edit by hand.
// Source kernel: {kernel.name}

{chr(10).join(resources)}

struct CasparParams
{{
    {chr(10).join("    " + p for p in params)}
}};

[[vk::binding({params_binding}, 0)]]
ConstantBuffer<CasparParams> params;

{helper_source()}

[shader("compute")]
[numthreads({kernel.block_size}, 1, 1)]
void computeMain(uint3 dispatchThreadID : SV_DispatchThreadID)
{{
    uint global_thread_idx = dispatchThreadID.x;
    if (global_thread_idx >= params.problem_size)
        return;

{register_decl}{code}
}}
"""
